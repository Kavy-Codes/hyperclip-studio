import { readFileSync, writeFileSync, readdirSync, statSync, existsSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const KIT = join(ROOT, 'vendor', 'herk-edit-kit');
const REGISTRY = join(KIT, 'style-library', 'registry.json');
const COMPONENTS = join(ROOT, 'components', 'manifest.json');
const CATALOG_JSON = join(ROOT, 'catalog.json');
const CATALOG_MD = join(ROOT, 'CATALOG.md');

function readJson(path) {
  return JSON.parse(readFileSync(path, 'utf8'));
}

function firstHeading(file) {
  const text = readFileSync(file, 'utf8');
  const line = text.split('\n').find((l) => l.startsWith('# '));
  return line ? line.slice(2).trim() : '';
}

function firstParagraph(file) {
  const text = readFileSync(file, 'utf8');
  const lines = text.split('\n').map((l) => l.trim()).filter(Boolean);
  const start = lines.findIndex((l) => l.startsWith('# '));
  return lines.slice(start + 1).find((l) => !l.startsWith('#')) || '';
}

function listDirs(path) {
  if (!existsSync(path)) return [];
  return readdirSync(path)
    .filter((name) => statSync(join(path, name)).isDirectory())
    .sort();
}

function loadRecipes() {
  const dir = join(ROOT, 'recipes');
  if (!existsSync(dir)) return [];
  return readdirSync(dir)
    .filter((f) => f.endsWith('.md'))
    .sort()
    .map((f) => {
      const file = join(dir, f);
      return {
        id: f.replace(/\.md$/, ''),
        title: firstHeading(file) || f,
        summary: firstParagraph(file),
        file: `recipes/${f}`
      };
    });
}

function loadTemplates() {
  const dir = join(ROOT, 'templates');
  if (!existsSync(dir)) return [];
  return listDirs(dir).map((name) => {
    const metaPath = join(dir, name, 'meta.json');
    const meta = existsSync(metaPath) ? readJson(metaPath) : {};
    return {
      id: name,
      title: meta.name && !String(meta.name).includes('{{') ? meta.name : name,
      width: meta.width || null,
      height: meta.height || null,
      fps: meta.fps || null,
      file: `templates/${name}/index.html`,
      brief: `templates/${name}/BRIEF.md`
    };
  });
}

function loadSceneTemplates() {
  const dir = join(KIT, 'style-templates');
  if (!existsSync(dir)) return [];
  return listDirs(dir).map((name) => {
    const design = join(dir, name, 'DESIGN.md');
    const readme = join(dir, 'README.md');
    return {
      id: name,
      title: firstHeading(design) || name,
      file: `vendor/herk-edit-kit/style-templates/${name}/index.html`,
      note: existsSync(readme) ? firstParagraph(readme) : ''
    };
  });
}

const registry = readJson(REGISTRY);
const manifest = readJson(COMPONENTS);

const styles = (registry.styles || []).map((s) => ({
  id: s.id,
  name: s.name,
  number: s.number,
  cardCount: s.cardCount,
  folder: s.folder,
  inspiration: s.inspiration,
  design: `vendor/herk-edit-kit/style-library/${s.folder}/DESIGN.md`,
  tokens: `vendor/herk-edit-kit/style-library/${s.folder}/tokens.css`
}));

const cards = [];
for (const style of registry.styles || []) {
  for (const card of style.cards || []) {
    cards.push({
      ...card,
      styleName: style.name,
      styleId: style.id,
      styleFolder: style.folder
    });
  }
}

const catalog = {
  generated: new Date().toISOString().slice(0, 10),
  source: 'STUDIO/vendor/herk-edit-kit/style-library/registry.json',
  styles,
  cards,
  components: manifest.components || [],
  recipes: loadRecipes(),
  templates: loadTemplates(),
  sceneTemplates: loadSceneTemplates()
};

function esc(value) {
  return String(value ?? '').replace(/\|/g, '\\|').replace(/\n/g, ' ');
}

function cardDuration(card) {
  const d = card.duration;
  if (!d) return '';
  if (typeof d === 'string') return d;
  if (d.min && d.max) return `${d.min}-${d.max}s`;
  if (d.min) return `${d.min}s+`;
  if (d.max) return `<=${d.max}s`;
  return '';
}

function renderMarkdown() {
  const lines = [];
  lines.push('# Studio catalog');
  lines.push('');
  lines.push(`Generated: ${catalog.generated}`);
  lines.push('');
  lines.push('This file is generated by `node STUDIO/scripts/catalog.mjs --write`.');
  lines.push('Use it to find a style, card, component, recipe or template before building from scratch.');
  lines.push('');
  lines.push('## Styles');
  lines.push('');
  lines.push('| Style | Cards | Folder | Design |');
  lines.push('|---|---:|---|---|');
  for (const s of styles) {
    lines.push(`| ${esc(s.name)} | ${s.cardCount} | \`${s.folder}\` | [DESIGN.md](${s.design}) |`);
  }
  lines.push('');
  lines.push('## Portrait components');
  lines.push('');
  lines.push('| ID | Type | Slots | File | Description |');
  lines.push('|---|---|---|---|---|');
  for (const c of catalog.components) {
    lines.push(`| \`${esc(c.id)}\` | ${esc(c.type)} | ${esc((c.slots || []).join(', '))} | \`${c.file}\` | ${esc(c.description)} |`);
  }
  lines.push('');
  lines.push('## Recipes');
  lines.push('');
  lines.push('| Recipe | File | Summary |');
  lines.push('|---|---|---|');
  for (const r of catalog.recipes) {
    lines.push(`| ${esc(r.title)} | \`${r.file}\` | ${esc(r.summary)} |`);
  }
  lines.push('');
  lines.push('## Project templates');
  lines.push('');
  lines.push('| Template | Canvas | File |');
  lines.push('|---|---|---|');
  for (const t of catalog.templates) {
    lines.push(`| ${esc(t.title)} | ${t.width || '?'}x${t.height || '?'} | \`${t.file}\` |`);
  }
  lines.push('');
  lines.push('## Scene templates');
  lines.push('');
  lines.push('| Template | File | Note |');
  lines.push('|---|---|---|');
  for (const t of catalog.sceneTemplates) {
    lines.push(`| ${esc(t.title)} | \`${t.file}\` | ${esc(t.note)} |`);
  }
  lines.push('');
  lines.push('## Card library');
  lines.push('');
  for (const s of styles) {
    const styleCards = cards.filter((c) => c.styleId === s.id);
    lines.push(`### ${s.name} (${styleCards.length})`);
    lines.push('');
    lines.push(`[DESIGN.md](${s.design}) · [tokens.css](${s.tokens})`);
    lines.push('');
    lines.push('| ID | Tier | Purpose | Slots | Duration | File |');
    lines.push('|---|---|---|---|---|---|');
    for (const c of styleCards) {
      lines.push(`| \`${esc(c.id)}\` | ${esc(c.tier)} | ${esc(c.purpose)} | ${esc((c.slots || []).join(', '))} | ${esc(cardDuration(c))} | \`${esc(c.file)}\` |`);
    }
    lines.push('');
  }
  return lines.join('\n');
}

function printSearch(query) {
  const q = query.toLowerCase();
  const matchedCards = cards.filter((c) =>
    [c.id, c.styleName, c.tier, c.purpose, ...(c.slots || [])].join(' ').toLowerCase().includes(q)
  );
  const matchedComponents = catalog.components.filter((c) =>
    [c.id, c.title, c.type, c.description, ...(c.tags || []), ...(c.slots || [])].join(' ').toLowerCase().includes(q)
  );
  const matchedRecipes = catalog.recipes.filter((r) =>
    [r.id, r.title, r.summary].join(' ').toLowerCase().includes(q)
  );

  console.log(`Search: ${query}\n`);
  console.log(`Cards: ${matchedCards.length}`);
  for (const c of matchedCards.slice(0, 40)) {
    console.log(`  ${c.id} | ${c.styleName} | ${c.tier} | ${c.purpose} | ${(c.slots || []).join(', ')} | ${c.file}`);
  }
  if (matchedCards.length > 40) console.log(`  ... ${matchedCards.length - 40} more`);
  console.log(`\nComponents: ${matchedComponents.length}`);
  for (const c of matchedComponents) {
    console.log(`  ${c.id} | ${c.type} | ${(c.slots || []).join(', ')} | ${c.file}`);
  }
  console.log(`\nRecipes: ${matchedRecipes.length}`);
  for (const r of matchedRecipes) {
    console.log(`  ${r.id} | ${r.title} | ${r.file}`);
  }
}

const args = process.argv.slice(2);
const searchIndex = args.indexOf('--search');
if (searchIndex !== -1) {
  const query = args[searchIndex + 1];
  if (!query) {
    console.error('Usage: node catalog.mjs --search <query>');
    process.exit(1);
  }
  printSearch(query);
  process.exit(0);
}

if (args.includes('--json')) {
  console.log(JSON.stringify(catalog, null, 2));
  process.exit(0);
}

writeFileSync(CATALOG_JSON, JSON.stringify(catalog, null, 2) + '\n');
writeFileSync(CATALOG_MD, renderMarkdown() + '\n');
console.log(`Wrote ${CATALOG_JSON}`);
console.log(`Wrote ${CATALOG_MD}`);
console.log(`Styles: ${styles.length}; cards: ${cards.length}; components: ${catalog.components.length}; recipes: ${catalog.recipes.length}; templates: ${catalog.templates.length}`);
